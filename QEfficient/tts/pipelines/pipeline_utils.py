from dataclasses import dataclass
from typing import Dict, List

import numpy as np

from QEfficient.diffusers.pipelines.pipeline_utils import ModulePerf
from QEfficient.utils import constants


@dataclass(frozen=True)
class QEffTTSOutput:
    """
    Output of a QEfficient text-to-speech pipeline.

    Attributes:
        audio: Waveform, float32, shape (num_samples,).
        sample_rate: Samples per second of ``audio``.
        speech_tokens: Speech tokens generated by the acoustic language model (end token included if reached).
        pipeline_module: Per-module wall times in seconds; a list for modules that run several times.
    """

    audio: np.ndarray
    sample_rate: int
    speech_tokens: np.ndarray
    pipeline_module: List[ModulePerf]

    @property
    def audio_seconds(self) -> float:
        return len(self.audio) / self.sample_rate

    def __repr__(self):
        total = 0.0
        lines = ["=" * 60, "QEfficient Text-to-Speech Pipeline Inference Report", "=" * 60]
        for module_perf in self.pipeline_module:
            perf = module_perf.perf
            seconds = sum(perf) if isinstance(perf, list) else perf
            total += seconds
            calls = f" ({len(perf)} calls)" if isinstance(perf, list) else ""
            lines.append(f"  {module_perf.module_name.replace('_', ' ').title():25s} {seconds:.4f} s{calls}")
        lines.append("-" * 60)
        lines.append(f"  {'Total':25s} {total:.4f} s for {self.audio_seconds:.2f} s of audio")
        if self.audio_seconds > 0:
            lines.append(f"  {'Real-time factor':25s} {total / self.audio_seconds:.3f}")
        lines.append("=" * 60)
        return "\n".join(lines)


def select_bucket(buckets: List[int], length: int) -> int:
    """Smallest compiled bucket that fits ``length``."""
    for bucket in sorted(buckets):
        if bucket >= length:
            return bucket
    raise ValueError(f"Length {length} exceeds the largest compiled bucket {max(buckets)}; compile a larger one.")


def check_bucket_config(config: Dict) -> None:
    """
    Check that the S3Gen length buckets of a compile config fit together: a flow-encoder bucket of ``n_tok`` tokens
    gives ``2 * n_tok`` mel frames and needs an estimator bucket of that size, and every HiFT decoder bucket needs an
    F0 bucket of the same mel length and produces 480 samples per mel frame.
    """
    modules = config["modules"]

    def sizes(module_name: str, symbol: str) -> List[int]:
        return sorted(spec[symbol] for spec in modules[module_name]["specializations"])

    frames_per_token = constants.CHATTERBOX_MEL_FRAMES_PER_TOKEN
    samples_per_frame = constants.CHATTERBOX_HIFT_SAMPLES_PER_MEL_FRAME
    for spec in modules["flow_encoder"]["specializations"]:
        if spec["n_frames"] != frames_per_token * spec["n_tok"]:
            raise ValueError(f"flow_encoder bucket {spec}: n_frames must be {frames_per_token} x n_tok.")
    if sizes("flow_estimator", "n_frames") != sizes("flow_encoder", "n_frames"):
        raise ValueError(
            f"flow_estimator n_frames {sizes('flow_estimator', 'n_frames')} must equal the flow_encoder n_frames "
            f"{sizes('flow_encoder', 'n_frames')}."
        )
    if sizes("hift_f0", "n_mel") != sizes("hift_decoder", "n_mel"):
        raise ValueError(
            f"hift_f0 n_mel {sizes('hift_f0', 'n_mel')} must equal the hift_decoder n_mel {sizes('hift_decoder', 'n_mel')}."
        )
    for spec in modules["hift_decoder"]["specializations"]:
        if spec["n_samples"] != samples_per_frame * spec["n_mel"]:
            raise ValueError(f"hift_decoder bucket {spec}: n_samples must be {samples_per_frame} x n_mel.")
